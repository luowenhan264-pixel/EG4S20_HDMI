"""Build reproducible 16px Chinese subtitle ROM; Windows SimSun font required."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
ROOT = Path(__file__).resolve().parents[1]
TEXTS = [
    '声音的波形不同，音色也会不同。按KEY4切换波形，听一听它们的区别。',
    '频率表示每秒振动的次数。对于单一纯音，频率越高，音调越高，周期越短。',
    '保持频率不变，调节幅度，观察波形高度和声音强弱的变化。幅度为零时，声音停止。',
    '多个声音可以叠加。青色为背景音乐，白色为最终输出。观察提示音加入前后的波形变化。',
]
chars = list(dict.fromkeys(' ' + ''.join(TEXTS)))
assert len(chars) <= 128 and max(map(len, TEXTS)) <= 64
font = ImageFont.truetype('C:/Windows/Fonts/simsun.ttc', 16)
lines = ['// Generated by tools/generate_science_osd.py. SimSun 16px, 1 bit.',
         'module science_subtitle_rom(input clk,input [1:0] page,input [5:0] cell_id,',
         'input [3:0] row,output reg [15:0] pixels);',
         'reg [7:0] code;', 'always @* begin', 'code=0;', 'case(page)']
for p, text in enumerate(TEXTS):
    lines += [f"2'd{p}:case(cell_id)"]
    lines += [f"6'd{i}:code=8'd{chars.index(c)};" for i,c in enumerate(text)]
    lines += ['default:code=0;endcase']
lines += ['endcase', 'end', 'reg [255:0] bitmap;', 'always @* begin', 'case(code)']
for code,c in enumerate(chars):
    img = Image.new('L', (16,16))
    ImageDraw.Draw(img).text((0,0), c, font=font, fill=255, anchor='lt')
    glyph = 0
    for y in range(16):
        bits = sum((img.getpixel((x,y)) >= 96) << (15-x) for x in range(16))
        glyph = (glyph << 16) | bits
    lines += [f"8'd{code}:bitmap=256'h{glyph:064x};"]
lines += ["default:bitmap=0;endcase", 'end', 'always @(posedge clk) pixels<=bitmap[(15-row)*16+:16];', 'endmodule']
(ROOT/'src/user_source/hdl_source/science_subtitle_rom.v').write_text('\n'.join(lines)+'\n')
print(f'Generated {len(chars)} glyphs; subtitle lengths: {list(map(len,TEXTS))}')
